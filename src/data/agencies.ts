export function agencyById(id: string): Agency {
  return AGENCIES.find((a) => a.id === id) ?? AGENCIES[0];
}

/** диапазон оценки → название полосы */
export function quoteBand(score: number): QuoteBand {
  if (score < 3) return 'awful';
  if (score < 5) return 'weak';
  if (score < 7) return 'decent';
  if (score < 8.5) return 'good';
  return 'great';
}
