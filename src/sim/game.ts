import type { GameState, Staff } from '../types';
import { BALANCE } from '../data/balance';
import { PALETTE } from '../data/names';
import { LABS } from '../data/labs';
import { Rng, randomSeed } from './rng';
import { refreshCandidates } from './staff';

export function createFounder(name: string, color: string): Staff {
  return {
    id: 'founder',
    name,
    role: 'founder',
    level: 'middle',
    research: 50,
    engineering: 50,
    speed: 50,
    salary: 0,
    burnout: 0,
    focus: 50,
    onProject: true,
    founder: true,
    vacationWeeks: 0,
    training: null,
    desk: 0,
    hiredWeek: 0,
    burnouts: 0,
    color,
  };
}

export function createGame(companyName: string, founderName: string, seed: number = randomSeed()): GameState {
  const rng = new Rng(seed);
  const accent = rng.pick(PALETTE);
  const game: GameState = {
    seed,
    rng: rng.state,
    companyName: companyName.trim() || 'Нейро Лабс',
    founderName: founderName.trim() || 'Основатель',
    accent,
    week: 0,
    speed: 1,
    money: BALANCE.start.money,
    fans: 0,
    hype: BALANCE.hype.base,
    rp: 0,
    office: 'garage',
    staff: [createFounder(founderName.trim() || 'Основатель', accent)],
    candidates: [],
    candidateRefreshIn: 0,
    nextStaffId: 1,
    project: null,
    nextProjectId: 1,
    models: [],
    nextModelId: 1,
    research: { done: [], current: null, progress: 0, discounts: [] },
    framework: { version: 0, name: 'Чужие библиотеки', features: [] },
    platforms: ['web'],
    gpus: ['g0'],
    gpu: 'g0',
    campaign: null,
    campaignsDone: [],
    contracts: { offers: [], active: [], nextUid: 1, offerCooldown: 0 },
    investorOffer: null,
    investor: null,
    investorCooldown: 24,
    grantCooldown: 13,
    grantOffers: [],
    grants: [],
    nextDealId: 1,
    loans: [],
    nextLoanId: 1,
    boosts: [],
    objects: [],
    nextObjectUid: 1,
    trends: [],
    marketMods: [],
    seenEvents: [],
    gpuCostMult: 1,
    revenueMult: 1,
    compliance: [],
    labs: LABS.map((lab) => ({ ...lab })),
    competitors: [],
    nextCompetitorId: 1,
    news: [],
    inbox: [],
    nextNewsId: 1,
    finance: [],
    comboMemory: {},
    achievements: [],
    stats: {
      releases: 0,
      totalRevenue: 0,
      totalExpenses: 0,
      bestRating: 0,
      bestModel: '',
      contractsDone: 0,
      contractsFailed: 0,
      hired: 0,
      quit: 0,
      researchDone: 0,
      campaigns: 0,
      frameworksBuilt: 0,
      versionsMade: 0,
      peakFans: 0,
      peakMoney: BALANCE.start.money,
      worstWeeklyLoss: 0,
      lowRatedReleases: 0,
      perfectReleases: 0,
      cleanReleases: 0,
      flagships: 0,
      chartTops: 0,
      lowRatedWeeks: 0,
      paradigmsUsed: [],
      lastReleaseWeek: 0,
    },
    insolvency: 0,
    gameover: null,
    tutorial: { active: true, step: 0 },
  };
  // на старте рынок труда уже предлагает первых кандидатов
  refreshCandidates(game, rng);
  return game;
}
